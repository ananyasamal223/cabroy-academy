import {Router} from "express";
import {protect,authorize} from "../middleware/auth.js";
import {listCourses,getCourse,createCourse,updateCourse,deleteCourse,getCourseMaterials} from "../controllers/course.controller.js";
import {listLessons,createLesson} from "../controllers/lesson.controller.js";
import {listReviews,upsertReview} from "../controllers/review.controller.js";
import {enroll} from "../controllers/enrollment.controller.js";
import {getProgress} from "../controllers/progress.controller.js";
import {issueCertificate} from "../controllers/certificate.controller.js";
import {submitProject} from "../controllers/project.controller.js";
const router=Router();
router.get("/",listCourses);
router.get("/:id",getCourse);
router.get("/:id/materials",protect,getCourseMaterials);
router.post("/",protect,authorize("admin","instructor"),createCourse);
router.patch("/:id",protect,authorize("admin","instructor"),updateCourse);
router.delete("/:id",protect,authorize("admin"),deleteCourse);
router.get("/:courseId/lessons",listLessons);
router.post("/:courseId/lessons",protect,authorize("admin","instructor"),createLesson);
router.get("/:courseId/reviews",listReviews);
router.post("/:courseId/reviews",protect,upsertReview);
router.post("/:courseId/enroll",protect,enroll);
router.get("/:courseId/progress",protect,getProgress);
router.post("/:courseId/certificate",protect,issueCertificate);
router.post("/:courseId/projects",protect,submitProject);
export default router;
